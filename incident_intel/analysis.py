"""Analysis orchestration - independent of any specific AI provider.

Flow: validate input -> pick provider -> provider returns raw JSON -> validate against
AnalysisResult -> apply rule-based severity floor -> derive escalation -> (optionally) persist.
"""
import time
import uuid

from pydantic import ValidationError as PydanticValidationError

from .errors import InvalidProviderResponse, ValidationError
from .logging_utils import get_logger
from .providers import get_provider
from .rules import ESCALATION, PRIORITY, max_severity, rule_severity
from .schemas import AnalysisResult, AnalyzeRequest
from .storage import utc_now

log = get_logger()


def validate_request(payload, settings):


    """Parse and validate a raw JSON payload into an AnalyzeRequest; raises ValidationError with a user-safe message."""
    if not isinstance(payload, dict):
        raise ValidationError("Request body must be a JSON object.")
    try:
        req = AnalyzeRequest(**{k: payload.get(k) for k in AnalyzeRequest.model_fields if k in payload})
    except PydanticValidationError as e:
        first = e.errors()[0]
        field = ".".join(str(p) for p in first["loc"]) or "request"
        raise ValidationError(f"Invalid {field}: {first['msg']}")
    req.description = (req.description or "").strip() if isinstance(req.description, str) else ""
    if len(req.description) < settings.min_description_chars:
        raise ValidationError(f"Describe the incident in at least {settings.min_description_chars} characters.")
    if len(req.description) > settings.max_description_chars:
        raise ValidationError(f"Description is too long (max {settings.max_description_chars} characters).")
    return req


class AnalysisService:


    """Runs one incident analysis end to end. Provider-agnostic: all AI specifics live in providers/."""
    def __init__(self, settings, storage=None):
        self.settings = settings
        self.storage = storage if settings.history_enabled else None

    def analyze(self, payload):

        """Validate -> call provider -> validate schema -> apply severity floor -> derive escalation -> persist. Returns the API payload. Provider failures propagate as ProviderError (never replaced by demo output)."""
        req = validate_request(payload, self.settings)
        provider = get_provider(req.provider, self.settings)

        started = time.monotonic()
        log.info("analysis started provider=%s chars=%d", provider.name, len(req.description))
        raw = provider.analyze(req.description, req.title, req.service, req.reported_severity)
        latency_ms = int((time.monotonic() - started) * 1000)

        try:
            result = AnalysisResult.model_validate(raw)
        except PydanticValidationError as e:
            fields = ", ".join(sorted({str(err["loc"][0]) for err in e.errors() if err["loc"]}))
            raise InvalidProviderResponse(f"The model's answer did not match the expected format (fields: {fields}).")

        model_severity = result.severity
        rules_severity, matched = rule_severity(f"{req.title or ''} {req.description}")
        final = max_severity(model_severity, rules_severity)
        escalated = final in ("Critical", "High") or result.needs_human_escalation
        result.severity = final
        result.suggested_priority = PRIORITY[final]
        result.needs_human_escalation = escalated
        if final != model_severity:
            result.severity_reasoning += (f" Severity raised from {model_severity} to {final} by safety rules "
                                          f"(matched: {', '.join(matched)}).")

        data = {
            "id": uuid.uuid4().hex[:12],
            "created_at": utc_now(),
            "provider": provider.name,
            "model": provider.model,
            "simulated": provider.simulated,
            "latency_ms": latency_ms,
            "input": {"title": req.title, "service": req.service, "reported_severity": req.reported_severity,
                      "description": req.description},
            "result": result.model_dump(),
            "severity_signals": {"model": model_severity, "rules": rules_severity or None,
                                 "matched_rules": matched, "reported": req.reported_severity, "final": final},
            "escalation": {"should_escalate": escalated, "route_to": ESCALATION[final][0]},
        }
        if provider.simulated:
            data["notice"] = "SIMULATED: generated by deterministic demo rules, not by an AI model."

        if self.storage:
            self.storage.save(
                {"id": data["id"], "title": req.title, "description": req.description, "service": req.service,
                 "reported_severity": req.reported_severity, "created_at": data["created_at"]},
                {"id": uuid.uuid4().hex[:12], "provider": provider.name, "model": provider.model,
                 "simulated": provider.simulated, "severity": final, "suggested_priority": result.suggested_priority,
                 "result": {**data["result"], "severity_signals": data["severity_signals"],
                            "escalation": data["escalation"]},
                 "latency_ms": latency_ms, "created_at": data["created_at"]})
        log.info("analysis done provider=%s severity=%s ms=%d", provider.name, final, latency_ms)
        return data
